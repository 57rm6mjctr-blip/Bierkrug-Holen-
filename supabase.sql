create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 18),
  group_code text null check (group_code is null or char_length(group_code) between 1 and 16),
  beers integer not null check (beers between 0 and 10000),
  created_at timestamptz not null default now()
);

alter table public.scores enable row level security;

drop policy if exists "Scores are readable by everyone" on public.scores;
create policy "Scores are readable by everyone"
on public.scores for select to anon using (true);

drop policy if exists "Anyone can submit a score" on public.scores;
create policy "Anyone can submit a score"
on public.scores for insert to anon with check (
  char_length(player_name) between 1 and 18
  and beers between 0 and 10000
  and (group_code is null or char_length(group_code) between 1 and 16)
);
